import { LOCALES, SITE_URL } from "./site";

/**
 * Canonical + hreflang for a page that exists in every locale.
 *
 * Pages must build their alternates with this instead of setting them inline:
 * in Next.js, a page that sets any `alternates` field REPLACES the parent's
 * whole `alternates` object. Setting only `canonical` therefore silently drops
 * the hreflang set — and pages that set nothing inherit the layout's canonical
 * (`/{locale}`), so they claim to be the homepage. Both bug classes are fixed
 * by routing every page through here.
 */
export function alternatesFor(locale: string, path = "") {
  const clean = path.replace(/^\/+/, "").replace(/\/+$/, "");
  const suffix = clean ? `/${clean}` : "";
  const languages: Record<string, string> = { "x-default": `/en${suffix}` };
  for (const l of LOCALES) languages[l] = `/${l}${suffix}`;
  return { canonical: `/${locale}${suffix}`, languages };
}

/**
 * Canonical for content published in English only (e.g. blog posts). The
 * non-English URL still resolves, but points its canonical at the English
 * version, so untranslated duplicates consolidate instead of competing.
 */
export function englishCanonical(path = "") {
  const clean = path.replace(/^\/+/, "").replace(/\/+$/, "");
  return clean ? `/en/${clean}` : "/en";
}

/** hreflang for English-only content: just the default + English itself. */
export function englishAlternates(path = "") {
  const canonical = englishCanonical(path);
  return { canonical, languages: { "x-default": canonical, en: canonical } };
}

/** Absolute URL helper for structured data and Open Graph. */
export function abs(path = "") {
  const clean = path.replace(/^\/+/, "");
  return clean ? `${SITE_URL}/${clean}` : SITE_URL;
}

